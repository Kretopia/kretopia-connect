  'Expand-phase compatibility: mirrors legacy profiles writes into profile_* split tables.';

DROP TRIGGER IF EXISTS trg_sync_profile_to_split ON public.profiles;
CREATE TRIGGER trg_sync_profile_to_split
  AFTER INSERT OR UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.sync_profile_to_split();
