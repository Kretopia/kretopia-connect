-- Profile table split — Phase B compatibility layer: sync trigger
-- Keeps the 5 profile_* split tables consistent with legacy `profiles` for EVERY writer
-- (356 frontend files + 107 edge functions) without converting them individually.
-- Fires AFTER INSERT/UPDATE on profiles and upserts each split row from NEW.
--
-- Safety notes:
--   * split-table CHECK constraints (ui_vibe, primary_intent) MATCH the existing
--     profiles constraints, so NEW always satisfies them — the trigger cannot reject
--     a write that profiles itself accepted.
--   * every NOT NULL split column maps to a NOT NULL profiles column.
--   * writes only to split tables (never back to profiles) → no recursion.
--   * split tables' own BEFORE UPDATE triggers maintain updated_at.
--   * profileService.updateProfile still dual-writes; that becomes redundant once this
--     trigger is live and can later be simplified to legacy-only writes.

